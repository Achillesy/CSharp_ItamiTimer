namespace ItamiTimer.App;

/// <summary>
/// 程序这一轮是当"督工"用还是当"钟"用。**启动时定一次，整个会话不再变**（§11.1 第 2 条）。
///
/// ⚠️ **绝不能做成"AW 断了就自动降级"**：那样杀掉 aw-server 就是一条免费刷时长的
/// 作弊路径，跟整个项目 fail-closed 的方向正相反，也会毁掉 §6.2 那个好性质
/// （临时不可达不影响最终正确性，因为历史在 aw-server 里）。
///
/// 任务开始之后 AW 才挂掉的，仍然按 §6.2 报「无法工作」，**不会**偷偷变成 <see cref="Pomodoro"/>。
///
/// AW 后启动的情况**不做任何补救**（用户 2026-07-28：「那就重新启动一次本程序」）。
/// 不做空闲重探、不做手动重试按钮 —— 少一个状态机，就少一类 bug。
/// </summary>
public enum AppMode
{
    /// <summary>约束模式：AW 就绪且 rules.json 读得出来。这才是这个程序的本职。</summary>
    Constrained,

    /// <summary>
    /// 纯番茄钟：AW 连不上，**或者** rules.json 读不了（§11.1 第 4 条）。
    ///
    /// 每一分钟都满格计入，灰弧永远不往前滑 —— "痛感全部来自表盘"这个命题在这里
    /// 不成立，因为此时它本来就只是个钟。
    /// </summary>
    Pomodoro,
}
